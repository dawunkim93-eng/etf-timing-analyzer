# ------------------------------------------------- 52주 고점 대비 낙폭 버킷
# 10년 백테스트에서 낙폭이 클수록 매수 성과가 좋다는 게 확인됐다.
# 다만 단조 증가가 아니라 봉우리 모양이다 — 30~35% 가 Sweet spot 이고,
# 40% 초과는 구조적 폭락(밸류 트랩)이라 오히려 떨어진다.
#
#   15~20%  평균 +1.26%  승률 56.2%
#   20~25%  평균 +2.06%  승률 59.3%
#   25~30%  평균 +4.52%  승률 64.2%
#   30~35%  평균 +7.41%  승률 67.6%   ← 곡점
#   35~40%  평균 +2.95%  승률 53.4%
#   40%+    평균 +4.86%  승률 55.9%
#
# 순위 재배치에 쓰는 **점수**가 아니라 정보 표기용 분류다.
# (라벨, 상한, 하한) — from_high_pct 는 음수라 상한이 더 작은 값이다.
DEPTH_BUCKETS: list[tuple[str, float, float]] = [
    ("15% 미만", 0.0, -15.0),
    ("15~20%", -15.0, -20.0),
    ("20~25%", -20.0, -25.0),
    ("25~30%", -25.0, -30.0),
    ("30~35%", -30.0, -35.0),
    ("35~40%", -35.0, -40.0),
    ("40%+", -40.0, -100.0),
]

# 곡점 버킷 — 검증 탭에서 강조 표시용
DEPTH_SWEET_SPOT = "30~35%"
# 표본이 이보다 적으면 "확정된 사실이 아니다" 고지로 표시한다
DEPTH_LOW_SAMPLE = 500


def depth_bucket(from_high_pct: float | None) -> str:
    """52주 고점 대비 낙폭(%) → 버킷 라벨."""
    if from_high_pct is None:
        return "확인 불가"
    for label, hi, lo in DEPTH_BUCKETS:
        if hi >= from_high_pct > lo:
            return label
    return "15% 미만" if from_high_pct > 0 else "40%+"


