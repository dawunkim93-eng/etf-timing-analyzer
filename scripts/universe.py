# ------------------------------------------------- 시장 국면 판정
# 1년 수익률 부호로 판정하면 안 된다.
#   한국 KODEX 200 이 1년 +80% 여서 "상승 국면" 으로 표시됐는데,
#   실제로는 52주 고점 대비 -43%, 200일선 아래였다.
#   1년 전 가격 대비라는 건 '추세'가 아니라 '과거 대비' 다.
#
# Lunde-Timmermann(2004) 20% 규칙을 쓴다 (참고 사이트와 동일):
#   직전 고점에서 20% 빠지면 하락장
#   직전 저점에서 20% 오르면 상승장
# 상태가 유지되므로 '한 달짜리 지수'가 아니라 '추세'를 읽는다.
#   10년 검증: 1년 방식은 국면을 22번 뒤집었고, 이 규칙은 6번이다.
REGIME_METHOD = "lt20"      # "lt20" | "ret12"
REGIME_THRESHOLD = 20.0     # 고점/저점 대비 반전 %
REGIME_HISTORY_YEARS = 10   # 국면 판정용 벤치마크 이력 (LT 는 전체 경로가 필요)

# ------------------------------------------------- 52주 고점 대비 낙폭 버킷
# 10년 백테스트에서 낙폭이 클수록 매수 성과가 좋다는 게 확인됐다.
# 다만 단조 증가가 아니라 봉우리 모양이다 — 30~35% 가 Sweet spot 이고,
# 40% 초과는 구조적 폭락(밸류 트랩)이라 오히려 떨어진다.
#
#   15~20%  평균 +1.26%  승률 56.2%
#   20~25%  평균 +2.06%  승률 59.3%
#   25~30%  평균 +4.52%  승률 64.2%
#   30~35%  평균 +7.41%  승률 67.6%   ← 곡점
#   35~40%  평균 +2.95%  승률 53.4%
#   40%+    평균 +4.86%  승률 55.9%
#
# 순위 재배치에 쓰는 **점수**가 아니라 정보 표기용 분류다.
# (라벨, 상한, 하한) — from_high_pct 는 음수라 상한이 더 작은 값이다.
DEPTH_BUCKETS: list[tuple[str, float, float]] = [
    ("15% 미만", 0.0, -15.0),
    ("15~20%", -15.0, -20.0),
    ("20~25%", -20.0, -25.0),
    ("25~30%", -25.0, -30.0),
    ("30~35%", -30.0, -35.0),
    ("35~40%", -35.0, -40.0),
    ("40%+", -40.0, -100.0),
]

# 곡점 버킷 — 검증 탭에서 강조 표시용
DEPTH_SWEET_SPOT = "30~35%"
# 표본이 이보다 적으면 "확정된 사실이 아니다" 고지로 표시한다
DEPTH_LOW_SAMPLE = 500


def depth_bucket(from_high_pct: float | None) -> str:
    """52주 고점 대비 낙폭(%) → 버킷 라벨."""
    if from_high_pct is None:
        return "확인 불가"
    for label, hi, lo in DEPTH_BUCKETS:
        if hi >= from_high_pct > lo:
            return label
    return "15% 미만" if from_high_pct > 0 else "40%+"


def yahoo_ticker(market: str, code: str) -> str:
    """내부 종목코드 → 야후 티커."""
    suffix = str(MARKETS[market]["yahoo_suffix"])
    return f"{code}{suffix}"


def display_ticker(market: str, code: str) -> str:
    """화면 표기용. 한국은 '.KS' 를 떼고 6자리 코드를 그대로 쓴다."""
    return code


def etf_rows(market: str) -> list[dict[str, str]]:
    """[{code, name, category, theme}] 형태."""
    return [
        {"code": c, "name": n, "category": cat, "theme": th}
        for c, n, cat, th in MARKETS[market]["etfs"]  # type: ignore[index]
    ]
